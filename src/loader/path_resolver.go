package loader

// =============================================================================
// ESSENTIAL PROCESS:
// Multi-tier configuration file path resolver evaluating explicit environment
// variables (CONFIG_PATH), caller stack heuristics, working directories, and binary names.
//
// DATA FLOW:
// 1. Input: Target profile/service name and environment variables.
// 2. Logic: Checks CONFIG_PATH, SHARED_CONFIG_PATH, caller dir, CWD, and exe dir in strict priority.
// 3. Output: Absolute or relative filepath pointing to the authoritative YAML configuration.
//
// KEY PARAMETERS:
// - CONFIG_PATH: Explicit filepath override.
// - SHARED_CONFIG_PATH: Shared configuration root or file path override.
// =============================================================================

import (
	"os"
	"path/filepath"
	"runtime"
	"strings"
)

// -----------------------------------------------------------------------------

// getCallerDir attempts to find the directory of the original source file (e.g. main.go)
// by traversing the call stack and skipping known library paths.
// This provides an extremely robust anchor for 'go run' where os.Executable is in /tmp/.
func getCallerDir() string {
	for i := 1; i < 25; i++ {
		_, file, _, ok := runtime.Caller(i)
		if !ok {
			break
		}
		// Skip list: stdlib and platform internal libs
		skip := false
		libsToSkip := []string{
			"runtime/", "reflect/", "testing/",
			"distributed-config", "microservice-toolbox", "universal-logger",
			"flexible-logger", "safe-socket", "message-serializers",
			"<autogenerated>",
		}
		for _, lib := range libsToSkip {
			if strings.Contains(file, lib) {
				skip = true
				break
			}
		}

		if !skip && file != "" {
			return filepath.Dir(file)
		}
	}
	return ""
}

// ResolveConfigPath handles the search logic for configuration files.
// It searches only for the targetName profile config in the binary directory (or caller source) and CWD.
//
// SEARCH ORDER (Locality First):
// 1. EXE/[targetName].yaml
// 2. CWD/[targetName].yaml
// -----------------------------------------------------------------------------

// collectSearchDirs returns a deduplicated list of directories starting from exeDir and cwd.
// When inside a repository/project (detected via .git, go.mod, Cargo.toml, or pyproject.toml
// within 4 parent levels), it walks up to the repository root so subpackage tests and nested
// binaries discover the repository's canonical standalone.yaml symlink without escaping isolated temp dirs.
func collectSearchDirs(exeDir, cwd string) []string {
	var dirs []string
	seen := make(map[string]bool)

	hasProjectMarker := func(dir string) bool {
		for _, marker := range []string{".git", "go.mod", "Cargo.toml", "pyproject.toml"} {
			if _, err := os.Stat(filepath.Join(dir, marker)); err == nil {
				return true
			}
		}
		return false
	}

	addWithParents := func(start string) {
		if start == "" {
			return
		}
		curr, err := filepath.Abs(start)
		if err != nil {
			curr = start
		}

		// Check if start or an ancestor up to 4 levels up has a project root marker
		maxDepth := 0
		probe := curr
		for d := 0; d <= 4 && probe != "" && probe != "/" && probe != "."; d++ {
			if hasProjectMarker(probe) {
				maxDepth = d
				break
			}
			parent := filepath.Dir(probe)
			if parent == probe {
				break
			}
			probe = parent
		}

		for depth := 0; depth <= maxDepth && curr != "" && curr != "/" && curr != "."; depth++ {
			if !seen[curr] {
				seen[curr] = true
				dirs = append(dirs, curr)
			}
			parent := filepath.Dir(curr)
			if parent == curr {
				break
			}
			curr = parent
		}
	}

	addWithParents(exeDir)
	addWithParents(cwd)
	return dirs
}

func ResolveConfigPath(targetName string) string {
	// 0. Explicit Environment Override (Highest Priority)
	if customPath := os.Getenv("CONFIG_PATH"); customPath != "" {
		if _, err := os.Stat(customPath); err == nil {
			return customPath
		}
	}
	if customPath := os.Getenv("SHARED_CONFIG_PATH"); customPath != "" {
		if _, err := os.Stat(customPath); err == nil {
			return customPath
		}
	}

	// If targetName is already an existing absolute or relative file path, use it directly
	if targetName != "" && (strings.HasSuffix(targetName, ".yaml") || strings.HasSuffix(targetName, ".yml")) {
		if _, err := os.Stat(targetName); err == nil {
			return targetName
		}
	}

	// 1. Determine Executable Context
	exePath, err := os.Executable()
	exeDir := ""
	if err == nil {
		exePathAbs, _ := filepath.Abs(exePath)
		exeDir = filepath.Dir(exePathAbs)
	}

	// 2. Smart Resolve for 'go run': find the directory of the caller's main.go
	if exeDir == "" || strings.Contains(exeDir, "go-build") || strings.Contains(exeDir, "T/go-build") {
		if callerDir := getCallerDir(); callerDir != "" {
			exeDir = callerDir
		}
	}

	cwd, _ := os.Getwd()
	searchDirs := collectSearchDirs(exeDir, cwd)

	// 3. Build Search Candidates (STRICT ORDER: Exact targetName first, then canonical standalone.yaml)
	var candidates []string
	if targetName != "" {
		for _, dir := range searchDirs {
			candidates = append(candidates, filepath.Join(dir, targetName+".yaml"))
		}
	}
	if targetName != "standalone" {
		for _, dir := range searchDirs {
			candidates = append(candidates, filepath.Join(dir, "standalone.yaml"))
		}
	}

	// 4. Search Loop
	for _, path := range candidates {
		if _, err := os.Stat(path); err == nil {
			return path
		}
	}

	// 5. Default Fallback
	baseDir := exeDir
	if baseDir == "" {
		baseDir = cwd
	}

	if targetName != "" {
		if baseDir != "" {
			return filepath.Join(baseDir, targetName+".yaml")
		}
		return targetName + ".yaml"
	}

	if baseDir != "" {
		return filepath.Join(baseDir, "config.yaml")
	}
	return "config.yaml"
}
